/* Map 2-bit per-channel levels to corrected RGB888. */
static inline void pebble_sunlight_correct(uint8_t r2, uint8_t g2, uint8_t b2,
                                           uint8_t *r, uint8_t *g, uint8_t *b)
{
    unsigned idx = (((unsigned)r2 & 0x3) << 4) |
                   (((unsigned)g2 & 0x3) << 2) |
                   ((unsigned)b2 & 0x3);
    *r = pebble_sunlight_lut[idx][0];
    *g = pebble_sunlight_lut[idx][1];
    *b = pebble_sunlight_lut[idx][2];
}
